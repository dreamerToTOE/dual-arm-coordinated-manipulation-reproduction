def _md_escape(s):
    return str(s).replace("|", "\\|")


def eq_markdown():
    lines = ["| 编号 | 论文公式（转录） | 位置 | 作用 | 官方代码位置 | 代码状态 |",
             "|---|---|---|---|---|---|"]
    for e in EQ:
        lines.append("| ({}) | `{}` | {} | {} | {} | `{}` |".format(
            e["id"], _md_escape(e["eq"]), _md_escape(e["loc"]), _md_escape(e["role"]),
            _md_escape(e["code"]), e["status"]))
    return "\n".join(lines)


def write_csv(path, cols, rows):
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, quoting=csv.QUOTE_MINIMAL, lineterminator="\n")
        w.writerow(cols)
        for r in rows:
            if len(r) != len(cols):
                raise SystemExit("column count mismatch in {}: {}".format(path, r[0]))
            w.writerow(r)


def write_eq_registry(path):
    cols = ["eq_id", "equation_plain", "paper_locator", "role", "official_code_locator",
            "code_status", "verdict_zh"]
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, quoting=csv.QUOTE_MINIMAL, lineterminator="\n")
        w.writerow(cols)
        for e in EQ:
            w.writerow([e["id"], e["eq"], e["loc"], e["role"], e["code"], e["status"], e["verdict"]])


def check_md(path, expected):
    if not os.path.exists(path):
        return None
    text = open(path, encoding="utf-8").read()
    if BEGIN not in text or END not in text:
        return "markers missing"
    block = text.split(BEGIN, 1)[1].split(END, 1)[0].strip("\n")
    if block.strip() != expected.strip():
        return "table drift detected"
    return "OK"


