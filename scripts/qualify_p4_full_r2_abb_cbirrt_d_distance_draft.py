def canonical(value):
    # All finite numeric fields compare as IEEE binary64, including signed zero;
    # booleans and container shapes stay distinct from ordinary numeric fields.
    if isinstance(value,bool):return value
    if type(value)in (float,int):return ['binary64',struct.pack('>d',value).hex()]
    if isinstance(value,list):return [canonical(x)for x in value]
    if isinstance(value,dict):return {k:canonical(v)for k,v in value.items()}
    return value
def exact(a,b):return canonical(a)==canonical(b)
